// Regenerates src/data/matrix.generated.ts from the prototype's praxis-data.js
// (window.PRAXIS). Run `npm run data:build` once the Mucho Matrix workbook is
// in the repo to rebuild from the spreadsheet instead.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const src = readFileSync(join(here, '..', 'prototype', 'praxis-data.js'), 'utf8')
const window = {}
new Function('window', src)(window)
const D = window.PRAXIS
for (const k of Object.keys(D.byKey)) D.byKey[k] = { acts: D.byKey[k].acts || [], inHouse: D.byKey[k].inHouse || 0 }
const acts = Object.values(D.byKey).reduce((n, d) => n + d.acts.length, 0)
const out = `// GENERATED by scripts/import-prototype-data.mjs — do not edit.
// ${D.hotels.length} hotels · ${D.dates.length} dates · ${acts} activity groups.
import type { Matrix } from '@/model/types'

export const MATRIX: Matrix = ${JSON.stringify(D)} as Matrix
`
writeFileSync(join(here, '..', 'src', 'data', 'matrix.generated.ts'), out)
console.log(`wrote matrix.generated.ts: ${D.hotels.length} hotels, ${D.dates.length} dates, ${acts} groups`)
